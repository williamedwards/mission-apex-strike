#!/usr/bin/env python3
"""Build PROMPT_LOG.md, the master prompt log, from its template and the captured prompts.

Reads docs/.prompt-log/records.json (written by scripts/prompt_log.py) and drops the
duplicate copies a continued Claude Code session carries into its new transcript (same
message id). The curated sections come from docs/master-prompt-log.template.md, where each
{{prompt:TEXT}} marker becomes the verbatim prompt containing TEXT (the first, in time
order), with its date and appendix number, so quoted prompts can't drift from the record.
The appendix lists every prompt with a one-line summary: the first sentence of the agent's
final saved reply, so it is the agent's own report, not an independent check.

Usage: python3 scripts/build_master_log.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECORDS = ROOT / "docs" / ".prompt-log" / "records.json"
LOG = ROOT / "PROMPT_LOG.md"
TEMPLATE = ROOT / "docs" / "master-prompt-log.template.md"
MARKER = "<!-- APPENDIX: everything below is generated by scripts/build_master_log.py -->"
AGENTS = {"claude": "Claude Code", "codex": "Codex CLI"}


def fence(text: str) -> str:
    """A code fence longer than any backtick run inside the text."""
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


def summary(record: dict) -> str:
    responses = [r["text"] for r in record.get("responses", []) if r.get("text", "").strip()]
    if not responses:
        return "(no saved reply)"
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", responses[-1])  # links → their text
    text = re.sub(r"[*_`#>]", "", text)
    text = " ".join(text.split())
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return first if len(first) <= 320 else first[:317].rstrip() + "…"


def quote(record: dict, number: int) -> str:
    """A curated prompt: when, which agent, where in the appendix, and the exact text."""
    prompt = record["prompt"].strip()
    f = fence(prompt)
    when = record["timestamp"][:16].replace("T", " ")
    agent = AGENTS.get(record["tool"], record["tool"])
    return f"**Date:** {when} UTC · **Agent:** {agent} · **Appendix:** #{number:03d}\n\n{f}text\n{prompt}\n{f}"


def expand(template: str, unique: list) -> str:
    def replace(match: re.Match) -> str:
        key = match.group(1)
        for number, record in enumerate(unique, 1):
            if key in record["prompt"]:
                return quote(record, number)
        raise SystemExit(f"No prompt contains {key!r}")
    return re.sub(r"\{\{prompt:(.+?)\}\}", replace, template)


def main() -> None:
    records = json.loads(RECORDS.read_text())
    seen, unique = set(), []
    for record in records:
        message = record["id"].rsplit(":", 1)[-1]
        if message in seen:
            continue
        seen.add(message)
        unique.append(record)
    unique.sort(key=lambda r: r["timestamp"])

    rename = next((i for i, r in enumerate(unique, 1) if "The Apex Inversion" in r["prompt"]), None)
    lines = [
        MARKER,
        "",
        "## 8. Complete Prompt List (Chronological)",
        "",
        f"All {len(unique)} prompts captured from the local Claude Code and Codex transcripts, in order "
        f"(times UTC). Duplicates that a continued session copies into its new transcript are removed "
        f"({len(records) - len(unique)} of {len(records)} records). Codex entries are the image prompts "
        "Claude Code sent to the Codex CLI. Each summary is the first sentence of the agent's final reply, "
        "as reported. The raw capture, with every saved reply, is [docs/prompt-log.md](docs/prompt-log.md).",
        "",
        "Not captured by the logger: messages sent while the agent was mid-turn. One such prompt, sent "
        f"during the title-screen work (after prompt {rename:03d}), was: "
        "*“Actually, I changed my mind, let's go with the name \"Mission: Apex Strike\"”*.",
        "",
    ]
    for number, record in enumerate(unique, 1):
        agent = AGENTS.get(record["tool"], record["tool"])
        prompt = record["prompt"].strip()
        f = fence(prompt)
        lines += [
            f"### {number:03d}. {record['timestamp'][:16].replace('T', ' ')} — {agent}",
            "",
            "**Exact prompt:**",
            "",
            f,
            prompt,
            f,
            "",
        ]
        if record.get("attachments"):
            lines += [f"*Attachments: {len(record['attachments'])} image(s).*", ""]
        lines += [f"**Response summary (reported):** {summary(record)}", ""]

    head = expand(TEMPLATE.read_text(), unique).rstrip() + "\n\n"
    LOG.write_text(head + "\n".join(lines) + "\n")
    print(f"{LOG.name}: {len(unique)} prompts in the appendix")


if __name__ == "__main__":
    main()
